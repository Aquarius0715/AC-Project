// Command ops generates ops/catalog_gen.go from the operation catalog, the write version catalog, the operation
// persistence map, the query catalog and service-contracts.ts (backend Go design §3), and the REST route table of the
// web apps' data access layer, service/web/shared/lib/routes.gen.ts (IR222). Run from service/api: go run ./cmd/gen/ops
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func read(path string) []map[string]string {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	recs, err := csv.NewReader(f).ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	var out []map[string]string
	for _, r := range recs[1:] {
		m := map[string]string{}
		for i, h := range recs[0] {
			m[h] = r[i]
		}
		out = append(out, m)
	}
	return out
}

// route is one rest_routes entry: "METHOD /v1/path" with an optional " [field=value]".
var route = regexp.MustCompile(`^(GET|POST|PUT|PATCH|DELETE) (/v1/\S+)(?: \[([A-Za-z]\w*)=([a-z_]+)\])?$`)

type restRoute struct{ method, path, field, value string }

func parseRoutes(op, column string) []restRoute {
	if column == "" {
		log.Fatalf("%s has no rest_routes", op)
	}
	var out []restRoute
	for _, entry := range strings.Split(column, ";") {
		m := route.FindStringSubmatch(entry)
		if m == nil {
			log.Fatalf("%s: malformed REST route %q", op, entry)
		}
		out = append(out, restRoute{m[1], m[2], m[3], m[4]})
	}
	return out
}

func goRoutes(rs []restRoute) string {
	var out []string
	for _, r := range rs {
		s := fmt.Sprintf("{Method: %q, Path: %q", r.method, r.path)
		if r.field != "" {
			s += fmt.Sprintf(", FixedField: %q, FixedValue: %q", r.field, r.value)
		}
		out = append(out, s+"}")
	}
	return strings.Join(out, ", ")
}

func tsRoutes(rs []restRoute) string {
	var out []string
	for _, r := range rs {
		s := fmt.Sprintf(`{ method: %q, path: %q`, r.method, r.path)
		if r.field != "" {
			s += fmt.Sprintf(`, fixed: [%q, %q]`, r.field, r.value)
		}
		out = append(out, s+" }")
	}
	return "[" + strings.Join(out, ", ") + "]"
}

func quoted(list []string) string {
	if len(list) == 0 {
		return "nil"
	}
	q := make([]string, len(list))
	for i, s := range list {
		q[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

// filterKinds reads Query.filters of service-contracts.ts: arrays are lists of strings, boolean and number keep
// their kind, everything else (IDs, instants, enums) is a string.
func filterKinds(path string) map[string]string {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	m := regexp.MustCompile(`filters\?:\{(.*?)\}\};`).FindSubmatch(src)
	if m == nil {
		log.Fatal("service-contracts.ts: Query.filters not found")
	}
	kinds := map[string]string{}
	for _, field := range strings.Split(string(m[1]), ";") {
		name, typ, ok := strings.Cut(field, "?:")
		if !ok {
			log.Fatalf("service-contracts.ts: unexpected filter %q", field)
		}
		switch {
		case strings.HasSuffix(typ, "[]"):
			kinds[name] = "{List: true}"
		case typ == "boolean":
			kinds[name] = "{Kind: KindBool}"
		case typ == "number":
			kinds[name] = "{Kind: KindNumber}"
		default:
			kinds[name] = "{}"
		}
	}
	return kinds
}

// generate returns catalog_gen.go, routes.gen.ts and contracts.gen.ts from the design documents.
func generate(docs string) ([]byte, []byte, []byte, int) {
	ops := read(docs + "/operation-catalog.csv")
	versions := map[string][]string{}
	for _, v := range read(docs + "/write-version-catalog.csv") {
		versions[v["operation"]] = append(versions[v["operation"]], fmt.Sprintf("{Branch: %q, Rule: %q}", v["branch"], v["expected_version"]))
	}
	modules := map[string]string{}
	for _, p := range read(docs + "/operation-persistence-map.csv") {
		modules[p["operation"]] = p["module"]
	}
	filters := map[string][]string{}
	for _, q := range read(docs + "/query-catalog.csv") {
		for _, f := range strings.Split(q["allowed_filters"], ",") {
			if f = strings.TrimSpace(f); f != "" {
				filters[q["operation"]] = append(filters[q["operation"]], f)
			}
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i]["operation"] < ops[j]["operation"] })

	var b, ts bytes.Buffer
	b.WriteString("// Code generated by cmd/gen/ops from docs/02-design; DO NOT EDIT.\n\npackage ops\n\n")
	b.WriteString("// Catalog lists every operation of operation-catalog.csv.\nvar Catalog = []Spec{\n")
	ts.WriteString("// Code generated by service/api/cmd/gen/ops from docs/02-design/operation-catalog.csv (rest_routes); DO NOT EDIT.\n\n")
	ts.WriteString("/** One REST route of a Core API operation (IR222): {field} path parameters named after the input fields they fill, and\n * optionally one input field the route fixes (payouts.transition at /approve sets action=approve). */\n")
	ts.WriteString("export type CoreRoute = { method: \"GET\" | \"POST\" | \"PUT\" | \"PATCH\" | \"DELETE\"; path: string; fixed?: readonly [string, string] };\n\n")
	ts.WriteString("/** The REST routes of every Core API operation. */\nexport const coreRoutes: Readonly<Record<string, readonly CoreRoute[]>> = {\n")
	for _, o := range ops {
		name := o["operation"]
		mode := "Read"
		if o["mode"] == "write" {
			mode = "Write"
		}
		if modules[name] == "" {
			log.Fatalf("%s missing in operation-persistence-map.csv", name)
		}
		rs := parseRoutes(name, o["rest_routes"])
		fmt.Fprintf(&b, "\t{Name: %q, Mode: %s, Module: %q, Authorization: %q, Versions: []VersionRule{%s}, DesignIDs: %q, Routes: []Route{%s}, Filters: %s},\n",
			name, mode, modules[name], strings.TrimSpace(o["authorization"]), strings.Join(versions[name], ", "), o["design_ids"], goRoutes(rs), quoted(filters[name]))
		fmt.Fprintf(&ts, "  %q: %s,\n", name, tsRoutes(rs))
	}
	b.WriteString("}\n\n")
	ts.WriteString("};\n")
	b.WriteString("// FilterKinds types the Query.filters fields of service-contracts.ts as query parameters (IR222); a filter\n// missing here is a string. Lists repeat the parameter or separate the values with commas.\n")
	b.WriteString("var FilterKinds = map[string]FilterKind{\n")
	kinds := filterKinds(docs + "/service-contracts.ts")
	names := make([]string, 0, len(kinds))
	for n := range kinds {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %s,\n", n, kinds[n])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	return src, ts.Bytes(), contracts(docs + "/service-contracts.ts"), len(ops)
}

// contracts copies the Core API's contract types into the web apps (IR313): coreOp / callOp type each operation's input
// by OperationContracts, so tsc checks every call against the contract.
func contracts(path string) []byte {
	body, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by service/api/cmd/gen/ops from docs/02-design/service-contracts.ts; DO NOT EDIT.\n")
	b.WriteString("// The Core API contract types for the web apps' calls (coreOp, callOp, coreAll; IR313).\n\n")
	b.Write(body)
	return b.Bytes()
}

func main() {
	docs := flag.String("docs", "../../docs/02-design", "docs/02-design directory")
	out := flag.String("out", "internal/ops/catalog_gen.go", "output file")
	web := flag.String("web", "../web/shared/lib/routes.gen.ts", "REST route table of the web apps")
	types := flag.String("contracts", "../web/shared/lib/contracts.gen.ts", "contract types of the web apps")
	flag.Parse()
	src, ts, ct, n := generate(*docs)
	for path, data := range map[string][]byte{*out: src, *web: ts, *types: ct} {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			log.Fatal(err)
		}
	}
	fmt.Printf("%d operations → %s, %s, %s\n", n, *out, *web, *types)
}
