// @vitest-environment node
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";
import { describe, expect, it } from "vitest";

// The <style> elements a library adds at run time without our nonce (DEC-75): Sonner (the shadcn/ui toasts) puts its
// stylesheet into the page when its module loads, and has no nonce option. The page CSP allows exactly that stylesheet by
// its SHA-256 hash (securityHeaders.ts), not every inline style. This test reads the stylesheet from the installed
// Sonner and keeps styleHashes.gen.ts current, so an upgrade that changes it fails here, not as refused toasts.
// Regenerate with UPDATE_STYLE_HASHES=1 npx vitest run shared/lib/__tests__/styleHashes.test.ts
const gen = fileURLToPath(new URL("../styleHashes.gen.ts", import.meta.url));

/** The CSS that sonner's module passes to its __insertCSS, and whether the <style> goes into the page before its text. */
function sonnerStylesheet(): { css: string; emptyFirst: boolean } {
  const file = createRequire(import.meta.url).resolve("sonner").replace(/index\.js$/, "index.mjs");
  const code = readFileSync(file, "utf8");
  const call = code.indexOf('__insertCSS("');
  expect(call, "sonner still adds its stylesheet through __insertCSS").toBeGreaterThan(0);
  const start = call + "__insertCSS(".length;
  let end = start + 1;
  while (end < code.length && !(code[end] === '"' && code[end - 1] !== "\\")) end++;
  const insert = code.slice(code.indexOf("function __insertCSS"), code.indexOf("}", code.indexOf("function __insertCSS")));
  return {
    css: runInNewContext(code.slice(start, end + 1)) as string, // the string literal's value, as the browser gets it
    emptyFirst: insert.indexOf("head.appendChild(style)") >= 0 && insert.indexOf("head.appendChild(style)") < insert.indexOf("createTextNode"),
  };
}

const hash = (css: string) => `'sha256-${createHash("sha256").update(css, "utf8").digest("base64")}'`;

describe("the CSP's style hashes", () => {
  it("styleHashes.gen.ts holds the hash of the stylesheet Sonner adds", () => {
    const sonner = sonnerStylesheet();
    // Sonner puts the empty <style> into the head before its text, and the browser checks it then too: the hash of the
    // empty text lets that moment pass without a refusal. An empty stylesheet styles nothing, and the text is checked
    // against the list again when it arrives.
    const hashes = [[hash(sonner.css), "sonner"], ...(sonner.emptyFirst ? [[hash(""), "sonner's <style> before its text"]] : [])];
    const text = `// Generated by shared/lib/__tests__/styleHashes.test.ts: the CSP hashes of the <style> elements libraries add at run time.\nexport const STYLE_HASHES: readonly string[] = [\n${hashes.map(([h, what]) => `  ${JSON.stringify(h)}, // ${what}\n`).join("")}];\n`;
    if (process.env.UPDATE_STYLE_HASHES === "1") writeFileSync(gen, text);
    expect(existsSync(gen) ? readFileSync(gen, "utf8") : "", "regenerate with UPDATE_STYLE_HASHES=1 (see the header)").toBe(text);
  });
});
