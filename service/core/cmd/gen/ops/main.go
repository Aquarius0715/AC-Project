// Command ops generates ops/catalog_gen.go from the operation catalog, the write version catalog
// and the operation persistence map (backend Go design §3). Run from backend/: go run ./cmd/gen/ops
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

func read(path string) []map[string]string {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	recs, err := csv.NewReader(f).ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	var out []map[string]string
	for _, r := range recs[1:] {
		m := map[string]string{}
		for i, h := range recs[0] {
			m[h] = r[i]
		}
		out = append(out, m)
	}
	return out
}

func main() {
	docs := flag.String("docs", "../../docs/02-design", "docs/02-design directory")
	out := flag.String("out", "ops/catalog_gen.go", "output file")
	flag.Parse()

	ops := read(*docs + "/operation-catalog.csv")
	versions := map[string][]string{}
	for _, v := range read(*docs + "/write-version-catalog.csv") {
		versions[v["operation"]] = append(versions[v["operation"]], fmt.Sprintf("{Branch: %q, Rule: %q}", v["branch"], v["expected_version"]))
	}
	modules := map[string]string{}
	for _, p := range read(*docs + "/operation-persistence-map.csv") {
		modules[p["operation"]] = p["module"]
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i]["operation"] < ops[j]["operation"] })

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gen/ops from docs/02-design; DO NOT EDIT.\n\npackage ops\n\n")
	b.WriteString("// Catalog lists every operation of operation-catalog.csv.\nvar Catalog = []Spec{\n")
	for _, o := range ops {
		name := o["operation"]
		mode := "Read"
		if o["mode"] == "write" {
			mode = "Write"
		}
		if modules[name] == "" {
			log.Fatalf("%s missing in operation-persistence-map.csv", name)
		}
		fmt.Fprintf(&b, "\t{Name: %q, Mode: %s, Module: %q, Authorization: %q, Versions: []VersionRule{%s}, DesignIDs: %q},\n",
			name, mode, modules[name], strings.TrimSpace(o["authorization"]), strings.Join(versions[name], ", "), o["design_ids"])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d operations → %s\n", len(ops), *out)
}
